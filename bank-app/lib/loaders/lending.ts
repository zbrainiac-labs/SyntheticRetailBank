import { DB, type LoaderDef } from "@/lib/loaders/types";

const REP = `${DB}.REP_AGG_V001`;
const CRM = `${DB}.CRM_AGG_V001`;

/**
 * The Streamlit loaders filter on AS_OF_DATE = CURRENT_DATE(); the dynamic
 * tables are refreshed once a day, so we read the latest available snapshot.
 */
const latest = (t: string) => `AS_OF_DATE = (SELECT MAX(AS_OF_DATE) FROM ${t})`;

/** Loaders of the ported lending page(s); names are "lending.<loader>". */
export const LOADERS_LENDING: Record<string, LoaderDef> = {
  "lending.portfolio": {
    sql: `SELECT TO_VARCHAR(AS_OF_DATE) AS AS_OF_DATE, COUNTRY, PRODUCT_TYPE, APPLICATION_STATUS, LOAN_COUNT,
                 TOTAL_REQUESTED_AMOUNT, AVG_REQUESTED_AMOUNT, MIN_REQUESTED_AMOUNT, MAX_REQUESTED_AMOUNT, AVG_TERM_MONTHS
            FROM ${REP}.LOAR_AGG_DT_PORTFOLIO_SUMMARY
           WHERE ${latest(`${REP}.LOAR_AGG_DT_PORTFOLIO_SUMMARY`)}
           ORDER BY TOTAL_REQUESTED_AMOUNT DESC`,
  },
  "lending.ltv": {
    sql: `SELECT LTV_BUCKET, LTV_BUCKET_SORT_ORDER, LOAN_COUNT, TOTAL_LOAN_AMOUNT, AVG_LTV_PCT,
                 TOTAL_COLLATERAL_VALUE, PCT_OF_TOTAL_LOANS
            FROM ${REP}.LOAR_AGG_DT_LTV_DISTRIBUTION
           WHERE ${latest(`${REP}.LOAR_AGG_DT_LTV_DISTRIBUTION`)}
           ORDER BY LTV_BUCKET_SORT_ORDER`,
  },
  "lending.funnel": {
    sql: `SELECT PRODUCT_TYPE, COUNTRY, CHANNEL, TOTAL_APPLICATIONS, APPROVED_COUNT, DECLINED_COUNT,
                 UNDER_REVIEW_COUNT, APPROVAL_RATE_PCT, DECLINE_RATE_PCT, AVG_REQUESTED_AMOUNT
            FROM ${REP}.LOAR_AGG_DT_APPLICATION_FUNNEL
           WHERE ${latest(`${REP}.LOAR_AGG_DT_APPLICATION_FUNNEL`)}
           ORDER BY TOTAL_APPLICATIONS DESC`,
  },
  "lending.affordability": {
    sql: `SELECT COUNTRY, AFFORDABILITY_RESULT, ASSESSMENT_COUNT, AVG_DTI_RATIO_PCT, AVG_DSTI_RATIO_PCT,
                 AVG_GROSS_INCOME, AVG_DEBT_OBLIGATIONS, PASS_RATE_PCT
            FROM ${REP}.LOAR_AGG_DT_AFFORDABILITY_SUMMARY
           WHERE ${latest(`${REP}.LOAR_AGG_DT_AFFORDABILITY_SUMMARY`)}
           ORDER BY COUNTRY, AFFORDABILITY_RESULT`,
  },
  "lending.compliance": {
    sql: `SELECT APPLICATION_ID, CUSTOMER_ID, COUNTRY, REQUESTED_AMOUNT, APPLICATION_STATUS,
                 REQUIRES_SANCTIONS_REVIEW, REQUIRES_EXPOSED_PERSON_REVIEW, OVERALL_RISK_RATING,
                 VULNERABLE_CUSTOMER_FLAG, COMPLIANCE_HOLD_FLAG, COMPLIANCE_STATUS,
                 TO_VARCHAR(APPLICATION_DATE_TIME) AS APPLICATION_DATE_TIME
            FROM ${REP}.LOAR_AGG_VW_COMPLIANCE_SCREENING
           WHERE COMPLIANCE_HOLD_FLAG = TRUE OR VULNERABLE_CUSTOMER_FLAG = TRUE
              OR OVERALL_RISK_RATING IN ('CRITICAL', 'HIGH')
           ORDER BY CASE COMPLIANCE_STATUS WHEN 'SANCTIONS_REVIEW' THEN 1 WHEN 'PEP_REVIEW' THEN 2
                         WHEN 'HIGH_RISK_REVIEW' THEN 3 ELSE 4 END,
                    APPLICATION_DATE_TIME DESC
           LIMIT 100`,
  },
  "lending.credit-bands": {
    sql: `SELECT CREDIT_SCORE_BAND, COUNT(*) AS CUSTOMERS
            FROM ${CRM}.CRMA_AGG_VW_CUSTOMER_360_ENRICHED
           WHERE CREDIT_SCORE_BAND IS NOT NULL
           GROUP BY CREDIT_SCORE_BAND
           ORDER BY CUSTOMERS DESC`,
  },
  "lending.risk-classes": {
    sql: `SELECT COALESCE(RISK_CLASSIFICATION, 'n/a') AS RISK_CLASSIFICATION, COUNT(*) AS CUSTOMERS
            FROM ${CRM}.CRMA_AGG_VW_CUSTOMER_360_ENRICHED
           GROUP BY 1
           ORDER BY CUSTOMERS DESC`,
  },
  "lending.customers": {
    sql: `SELECT CUSTOMER_ID, FULL_NAME, COUNTRY, CREDIT_SCORE_BAND, RISK_CLASSIFICATION, ACCOUNT_TIER
            FROM ${CRM}.CRMA_AGG_VW_CUSTOMER_360_ENRICHED
           ORDER BY CUSTOMER_ID
           LIMIT 10000`,
    maxRows: 10000,
  },
};
