import { DB, type LoaderDef } from "@/lib/loaders/types";

const CRM = `${DB}.CRM_AGG_V001`;

/** Loaders of the ported wealth page(s); names are "wealth.<loader>". */
export const LOADERS_WEALTH: Record<string, LoaderDef> = {
  /** one row per advisor (a few dozen); KPIs and charts are derived client-side */
  "wealth.advisors": {
    sql: `SELECT EMPLOYEE_ID, ADVISOR_NAME, TOTAL_CLIENTS, WORKLOAD_STATUS, AVAILABLE_CAPACITY,
                 TOTAL_PORTFOLIO_VALUE, REGION, COUNTRY, CAPACITY_UTILIZATION_PCT, TOTAL_TRANSACTIONS,
                 HIGH_RISK_CLIENTS, PERFORMANCE_RATING, EMPLOYMENT_STATUS
            FROM ${CRM}.EMPA_AGG_VW_ADVISOR_PERFORMANCE_ENRICHED
           ORDER BY AVAILABLE_CAPACITY DESC`,
    maxRows: 2000,
  },
  /** aggregated KPIs (used for parity checks) */
  "wealth.kpis": {
    sql: `SELECT COUNT(*) AS TOTAL_ADVISORS,
                 SUM(TOTAL_CLIENTS) AS TOTAL_CLIENTS,
                 SUM(TOTAL_PORTFOLIO_VALUE) AS TOTAL_PORTFOLIO_VALUE,
                 COUNT_IF(WORKLOAD_STATUS = 'AVAILABLE') AS AVAILABLE,
                 COUNT_IF(WORKLOAD_STATUS = 'AT_CAPACITY') AS AT_CAPACITY,
                 SUM(AVAILABLE_CAPACITY) AS TOTAL_SLOTS,
                 AVG(CAPACITY_UTILIZATION_PCT) AS AVG_UTILIZATION_PCT
            FROM ${CRM}.EMPA_AGG_VW_ADVISOR_PERFORMANCE_ENRICHED`,
  },
  "wealth.team": {
    sql: `SELECT TEAM_LEADER_ID, REGION, TO_VARCHAR(HIRE_DATE) AS HIRE_DATE, TL_PERFORMANCE_RATING, SUPER_LEADER_ID,
                 TOTAL_ADVISORS, ACTIVE_ADVISORS, AVG_ADVISOR_PERFORMANCE, MIN_ADVISOR_PERFORMANCE,
                 MAX_ADVISOR_PERFORMANCE, TOTAL_CLIENTS, HIGH_RISK_CLIENTS, TOTAL_TEAM_AUM, AVG_CLIENT_BALANCE,
                 AVG_CLIENTS_PER_ADVISOR, TEAM_CAPACITY_UTILIZATION_PCT, TEAM_AVAILABLE_CAPACITY,
                 COUNTRIES_COVERED, COUNTRY_LIST
            FROM ${CRM}.EMPA_AGG_DT_TEAM_LEADER_DASHBOARD
           ORDER BY TOTAL_TEAM_AUM DESC`,
  },
};
