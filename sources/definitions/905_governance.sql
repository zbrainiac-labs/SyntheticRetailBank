-- Data quality gates (system DMFs). Need EXECUTE DATA METRIC FUNCTION ON ACCOUNT for CICD
-- (granted in pre_deploy.sql). Target DTs carry DATA_METRIC_SCHEDULE = '60 MINUTE'.
-- Expectations make them part of EXECUTE DCM PROJECT ... TEST ALL; FRESHNESS is in seconds
-- (7200 = twice the 60-minute target lag).
ATTACH DATA METRIC FUNCTION SNOWFLAKE.CORE.ROW_COUNT
    TO DYNAMIC TABLE {{ db }}.{{ crm_agg }}.CRMI_AGG_DT_CUSTOMER_PII
    ON ()
    EXPECTATION CUSTOMER_PII_NOT_EMPTY (VALUE > 0);

ATTACH DATA METRIC FUNCTION SNOWFLAKE.CORE.NULL_PERCENT
    TO DYNAMIC TABLE {{ db }}.{{ crm_agg }}.CRMI_AGG_DT_CUSTOMER_PII
